import type { Skill, SavedStackItem } from '@/types'

export type DockerInputItem = Skill | SavedStackItem

export interface DockerSecuritySpec {
  user: string
  uid: number
  gid: number
  memoryLimit: string
  cpuLimit: string
  capabilitiesDropped: string[]
  capabilitiesAdded: string[]
  noNewPrivileges: boolean
  readOnlyRoot: boolean
}

export const DOCKER_SECURITY_SPEC: DockerSecuritySpec = {
  user: 'agent',
  uid: 1001,
  gid: 1001,
  memoryLimit: '4G',
  cpuLimit: '2.0',
  capabilitiesDropped: ['ALL'],
  capabilitiesAdded: ['CHOWN', 'SETUID', 'SETGID'],
  noNewPrivileges: true,
  readOnlyRoot: false, // writable workspace mount, protected system
}

/**
 * Generates an isolated, non-root Dockerfile.agent tailored for autonomous coding agents.
 */
export function generateAgentDockerfile(stack: DockerInputItem[]): string {
  const p0Skills = stack.filter((s) => s.priority === 'P0')
  const skillIds = stack.map((s) => s.id).join(', ')

  return `# ==============================================================================
# 🐳 SkillDock Sandboxed Autonomous Agent Container (Dockerfile.agent)
# Enterprise-grade AI Agent Runtime with non-root privilege isolation & resource boundaries
# Generated by SkillDock v3.0 (https://nownitya.github.io/Ai-Models-List/)
# Active Stack: ${stack.length} skills (${p0Skills.length} P0 critical guards)
# Skills: ${skillIds || 'none'}
# ==============================================================================

FROM node:22-bookworm-slim

LABEL maintainer="SkillDock Community <noreply@github.com>" \\
      description="Isolated sandboxed environment for autonomous AI coding agents" \\
      version="3.0.0"

# 1. Install core runtime toolchains: Python 3.12, Git, curl, jq, procps
RUN apt-get update && apt-get install -y --no-install-recommends \\
    python3 \\
    python3-pip \\
    python3-venv \\
    git \\
    curl \\
    ca-certificates \\
    jq \\
    procps \\
    && rm -rf /var/lib/apt/lists/*

# 2. Establish unprivileged agent user & group (UID/GID 1001)
# Enforces enterprise boundary: agent NEVER runs as root inside the container
RUN groupadd -g ${DOCKER_SECURITY_SPEC.gid} ${DOCKER_SECURITY_SPEC.user} && \\
    useradd -u ${DOCKER_SECURITY_SPEC.uid} -g ${DOCKER_SECURITY_SPEC.user} -m -s /bin/bash ${DOCKER_SECURITY_SPEC.user}

# 3. Scaffold isolated workspace and configuration caches
WORKDIR /workspace
RUN mkdir -p /workspace/.agents /home/${DOCKER_SECURITY_SPEC.user}/.cache && \\
    chown -R ${DOCKER_SECURITY_SPEC.user}:${DOCKER_SECURITY_SPEC.user} /workspace /home/${DOCKER_SECURITY_SPEC.user}

# 4. Switch to non-root developer user
USER ${DOCKER_SECURITY_SPEC.user}
ENV HOME=/home/${DOCKER_SECURITY_SPEC.user} \\
    PATH="/home/${DOCKER_SECURITY_SPEC.user}/.local/bin:/workspace/node_modules/.bin:$PATH" \\
    NODE_ENV=development \\
    SKILLDOCK_SANDBOX=1

# 5. Pre-install open skill ecosystem CLI packages
RUN npm install --no-audit --no-fund --global @skilldock/cli npx skills || true

# 6. Container healthcheck: verify node, python, and git availability
HEALTHCHECK --interval=30s --timeout=5s --start-period=5s --retries=3 \\
    CMD node -v && python3 --version && git --version || exit 1

# 7. Default Entrypoint: start interactive unprivileged developer shell
CMD ["/bin/bash"]
`
}

/**
 * Generates an enterprise compose.agent.yml with memory capping, CPU limits,
 * and secure workspace bind mounts.
 */
export function generateAgentCompose(stack: DockerInputItem[]): string {
  const skillSummary = stack.map((s) => `#   - ${s.name} (/${s.scoped})`).join('\n')

  return `# ==============================================================================
# 🐙 SkillDock Sandboxed Agent Compose (compose.agent.yml)
# Restricts CPU, RAM, and host access to protect against destructive commands (rm -rf)
# Generated by SkillDock v3.0 (https://nownitya.github.io/Ai-Models-List/)
# Active Stack (${stack.length} skills):
${skillSummary || '#   (No skills selected)'}
# ==============================================================================

services:
  agent-sandbox:
    build:
      context: .
      dockerfile: Dockerfile.agent
    container_name: skilldock-agent-sandbox
    user: "${DOCKER_SECURITY_SPEC.uid}:${DOCKER_SECURITY_SPEC.gid}"
    working_dir: /workspace

    # 🔒 Controlled Filesystem Mounts
    volumes:
      # Mount current repository workspace with read-write access
      - ./:/workspace:rw
      # Protect host Git identity & credentials from modification or exfiltration
      - /workspace/.git/config:/workspace/.git/config:ro

    # 🔑 Environment Variables (Pass through API keys securely from host)
    environment:
      - ANTHROPIC_API_KEY=\${ANTHROPIC_API_KEY:-}
      - OPENAI_API_KEY=\${OPENAI_API_KEY:-}
      - GEMINI_API_KEY=\${GEMINI_API_KEY:-}
      - DEEPSEEK_API_KEY=\${DEEPSEEK_API_KEY:-}
      - SKILLDOCK_STACK_PATH=/workspace/.skilldock-stack.json
      - CI=true

    # 🛡️ Enterprise Hardened Security Profile
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL
    cap_add:
      - CHOWN
      - SETUID
      - SETGID

    # 🛑 Strict Resource Ceilings (Prevents fork-bombs and runaway loops)
    deploy:
      resources:
        limits:
          cpus: '${DOCKER_SECURITY_SPEC.cpuLimit}'
          memory: ${DOCKER_SECURITY_SPEC.memoryLimit}
        reservations:
          cpus: '0.5'
          memory: 1G

    # Interactive terminal support
    stdin_open: true
    tty: true
`
}
